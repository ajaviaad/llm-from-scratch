"""Deterministic UTF-8 byte tokenizers, implemented with the standard library.

The byte baseline always has 256 tokens. BPE starts with those bytes and learns
ordered pair merges on training documents only. It has no unknown-token ID,
normalization, special tokens, pre-tokenizer, or cross-document training pair.

This deliberately readable reference rescans the corpus for each learned merge.
It is intended for small experiments, not industrial tokenizer training. The
bounds below limit training size and the expansion of untrusted merge metadata.
"""
from collections import Counter
import hashlib
import json

FORMAT_VERSION = 1
BYTE_VOCABULARY = 256
MAX_VOCABULARY = 4096
MAX_TOKEN_BYTES = 4096
MAX_TRAINING_BYTES = 1_000_000
MAX_TRAINING_DOCUMENTS = 10_000


def _utf8(text):
    if not isinstance(text, str):
        raise TypeError('text must be a string')
    # Strict encoding rejects unpaired surrogates rather than silently changing
    # the training corpus. All ordinary Unicode text is reversible.
    return text.encode('utf-8', errors='strict')


def _digest(metadata):
    canonical = json.dumps(metadata, sort_keys=True, separators=(',', ':'),
                           ensure_ascii=True, allow_nan=False).encode('ascii')
    return hashlib.sha256(canonical).hexdigest()


def _decode(ids, pieces, errors):
    if errors not in ('replace', 'strict'):
        raise ValueError("errors must be 'replace' or 'strict'")
    try:
        iterator = iter(ids)
    except TypeError as exc:
        raise ValueError('token IDs must be an iterable of integers') from exc
    chunks = []
    for token in iterator:
        # bool is an int subclass; accepting it hides malformed token data.
        if type(token) is not int or not 0 <= token < len(pieces):
            raise ValueError('token ID must be an integer within the vocabulary')
        chunks.append(pieces[token])
    return b''.join(chunks).decode('utf-8', errors=errors)


def _merge_pair(tokens, pair, replacement):
    """Replace nonoverlapping occurrences left to right, including repeats."""
    result = []
    index = 0
    left, right = pair
    while index < len(tokens):
        if (index + 1 < len(tokens) and tokens[index] == left
                and tokens[index + 1] == right):
            result.append(replacement)
            index += 2
        else:
            result.append(tokens[index])
            index += 1
    return result


def _check_header(data, kind, fields):
    if type(data) is not dict or set(data) != fields:
        raise ValueError('tokenizer metadata has missing or unexpected fields')
    if data['kind'] != kind or type(data['kind']) is not str:
        raise ValueError(f"tokenizer kind must be {kind!r}")
    if type(data['version']) is not int or data['version'] != FORMAT_VERSION:
        raise ValueError('unsupported tokenizer format version')


class ByteTokenizer:
    """The reversible UTF-8 baseline, with token ID equal to byte value."""
    kind = 'byte'
    vocab_size = BYTE_VOCABULARY
    _pieces = tuple(bytes([value]) for value in range(BYTE_VOCABULARY))

    def encode(self, text):
        return list(_utf8(text))

    def decode(self, ids, errors='replace'):
        """Decode complete token sequences; generated bytes can be invalid UTF-8."""
        return _decode(ids, self._pieces, errors)

    def to_dict(self):
        return {'kind': self.kind, 'version': FORMAT_VERSION}

    @classmethod
    def from_dict(cls, data):
        _check_header(data, 'byte', {'kind', 'version'})
        return cls()

    def digest(self):
        """SHA-256 of canonical metadata, suitable for checkpoint binding."""
        return _digest(self.to_dict())


class BPETokenizer:
    """Ordered byte-pair merges; new token ID is 256 plus its merge rank.

    Use ``train`` for a new tokenizer or ``from_dict`` for a saved one. The
    constructor also accepts a list/tuple of integer pairs for small examples.
    The merge sequence is immutable after construction.
    """
    kind = 'bpe'

    def __init__(self, merges=()):
        if type(merges) not in (list, tuple):
            raise ValueError('merges must be a list or tuple of pairs')
        if len(merges) > MAX_VOCABULARY - BYTE_VOCABULARY:
            raise ValueError(f'vocabulary cannot exceed {MAX_VOCABULARY}')
        pieces = list(ByteTokenizer._pieces)
        checked = []
        seen = set()
        for rank, pair in enumerate(merges):
            if type(pair) not in (list, tuple) or len(pair) != 2:
                raise ValueError('each merge must contain exactly two token IDs')
            token_id = BYTE_VOCABULARY + rank
            if any(type(value) is not int or not 0 <= value < token_id
                   for value in pair):
                raise ValueError('merge operands must refer to earlier token IDs')
            pair = tuple(pair)
            if pair in seen:
                raise ValueError('duplicate merge pair')
            size = len(pieces[pair[0]]) + len(pieces[pair[1]])
            if size > MAX_TOKEN_BYTES:
                raise ValueError(f'a merged token cannot exceed {MAX_TOKEN_BYTES} bytes')
            pieces.append(pieces[pair[0]] + pieces[pair[1]])
            checked.append(pair)
            seen.add(pair)
        self._merges = tuple(checked)
        self._pieces = tuple(pieces)

    @property
    def merges(self):
        return self._merges

    @property
    def vocab_size(self):
        return len(self._pieces)

    @classmethod
    def train(cls, documents, vocab_size=320, min_frequency=2):
        """Learn merges from a list of documents without joining boundaries.

        Adjacent-pair frequencies count overlapping occurrences. The highest
        frequency wins; ties use ascending ``(left_id, right_id)``. Each winning
        pair is replaced nonoverlappingly from left to right in every document.
        Training stops at the target vocabulary, below ``min_frequency``, or
        when no eligible pair remains. The actual vocabulary can be smaller.
        """
        if type(documents) is not list or len(documents) > MAX_TRAINING_DOCUMENTS:
            raise ValueError(f'documents must be a list of at most {MAX_TRAINING_DOCUMENTS} strings')
        if (type(vocab_size) is not int
                or not BYTE_VOCABULARY <= vocab_size <= MAX_VOCABULARY):
            raise ValueError(f'vocab_size must be an integer from 256 to {MAX_VOCABULARY}')
        if type(min_frequency) is not int or min_frequency < 1:
            raise ValueError('min_frequency must be a positive integer')
        sequences = []
        total_bytes = 0
        for document in documents:
            raw = _utf8(document)
            total_bytes += len(raw)
            if total_bytes > MAX_TRAINING_BYTES:
                raise ValueError(f'training text cannot exceed {MAX_TRAINING_BYTES} UTF-8 bytes')
            sequences.append(list(raw))
        lengths = [1] * BYTE_VOCABULARY
        merges = []
        while BYTE_VOCABULARY + len(merges) < vocab_size:
            counts = Counter()
            for tokens in sequences:
                counts.update(zip(tokens, tokens[1:]))
            eligible = [pair for pair, count in counts.items()
                        if count >= min_frequency
                        and lengths[pair[0]] + lengths[pair[1]] <= MAX_TOKEN_BYTES]
            if not eligible:
                break
            pair = min(eligible, key=lambda item: (-counts[item], item))
            new_id = BYTE_VOCABULARY + len(merges)
            sequences = [_merge_pair(tokens, pair, new_id) for tokens in sequences]
            lengths.append(lengths[pair[0]] + lengths[pair[1]])
            merges.append(pair)
        return cls(merges)

    def encode(self, text):
        tokens = list(_utf8(text))
        # A later merge only creates a higher token ID. It cannot create an
        # occurrence of an earlier pair, so one ordered pass per rank suffices.
        for rank, pair in enumerate(self._merges):
            tokens = _merge_pair(tokens, pair, BYTE_VOCABULARY + rank)
        return tokens

    def decode(self, ids, errors='replace'):
        return _decode(ids, self._pieces, errors)

    def to_dict(self):
        return {'kind': self.kind, 'version': FORMAT_VERSION,
                'merges': [list(pair) for pair in self._merges]}

    @classmethod
    def from_dict(cls, data):
        _check_header(data, 'bpe', {'kind', 'version', 'merges'})
        # Serialized metadata must be JSON-shaped, even if the constructor also
        # permits immutable tuples for hand-written Python examples.
        if type(data['merges']) is not list or any(type(p) is not list for p in data['merges']):
            raise ValueError('serialized merges must be a list of two-item lists')
        return cls(data['merges'])

    def digest(self):
        return _digest(self.to_dict())


def tokenizer_from_dict(data):
    """Load either stable schema without executing code or accepting extras."""
    if type(data) is not dict or type(data.get('kind')) is not str:
        raise ValueError('tokenizer metadata needs a string kind')
    if data['kind'] == 'byte':
        return ByteTokenizer.from_dict(data)
    if data['kind'] == 'bpe':
        return BPETokenizer.from_dict(data)
    raise ValueError('unknown tokenizer kind')
